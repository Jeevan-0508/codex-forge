import fs from 'node:fs';
import path from 'node:path';

function readSkill(sourceDir) {
  const direct = path.join(sourceDir, 'SKILL.md');
  if (fs.existsSync(direct)) return { file: direct, text: fs.readFileSync(direct, 'utf8') };
  const markdown = fs.readdirSync(sourceDir).filter((name) => name.toLowerCase().endsWith('.md'));
  if (markdown.length === 1) {
    const file = path.join(sourceDir, markdown[0]);
    return { file, text: fs.readFileSync(file, 'utf8') };
  }
  throw new Error('Expected SKILL.md or exactly one Markdown file');
}

function frontmatter(text) {
  const match = text.match(/^---\s*\n([\s\S]*?)\n---\s*\n([\s\S]*)$/);
  if (!match) throw new Error('Skill Markdown must have YAML frontmatter');
  const fields = {};
  for (const line of match[1].split(/\r?\n/)) {
    const separator = line.indexOf(':');
    if (separator > 0) fields[line.slice(0, separator).trim()] = line.slice(separator + 1).trim();
  }
  return { fields, body: match[2].trim() };
}

export function convertSkill(sourceDir, outDir, { dryRun = false } = {}) {
  const source = path.resolve(sourceDir);
  const target = path.resolve(outDir);
  if (!fs.existsSync(source) || !fs.statSync(source).isDirectory()) throw new Error('source must be a directory');
  if (target === source || target.startsWith(`${source}${path.sep}`)) throw new Error('output must not be inside source');
  const input = readSkill(source);
  const parsed = frontmatter(input.text);
  const name = parsed.fields.name || path.basename(source).toLowerCase().replace(/[^a-z0-9-]+/g, '-');
  const description = parsed.fields.description || 'Converted Codex skill';
  const output = `---\nname: ${name}\ndescription: ${description}\nmetadata:\n  generated-by: codex-forge\n  source-format: claude-skill\n---\n\n${parsed.body}\n`;
  const conversion = `# Conversion record\n\n- Source: ${input.file}\n- Generated by: codex-forge\n- Verification: conversion-only; runtime behavior is not verified\n- Safety: no upstream scripts or dependencies were executed\n`;
  if (!dryRun) {
    fs.mkdirSync(target, { recursive: true });
    fs.writeFileSync(path.join(target, 'SKILL.md'), output, 'utf8');
    fs.writeFileSync(path.join(target, 'CONVERSION.md'), conversion, 'utf8');
  }
  return { source, target, dryRun, files: ['SKILL.md', 'CONVERSION.md'], name };
}
